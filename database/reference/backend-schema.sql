CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT,
    password TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('farmer', 'owner')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS farm_location TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS farm_latitude DOUBLE PRECISION;
ALTER TABLE users ADD COLUMN IF NOT EXISTS farm_longitude DOUBLE PRECISION;
ALTER TABLE users ADD COLUMN IF NOT EXISTS allowed_roles TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[];
ALTER TABLE users ADD COLUMN IF NOT EXISTS selected_location TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS selected_latitude DOUBLE PRECISION;
ALTER TABLE users ADD COLUMN IF NOT EXISTS selected_longitude DOUBLE PRECISION;
ALTER TABLE users ADD COLUMN IF NOT EXISTS is_suspended BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE users
SET allowed_roles = ARRAY[role]
WHERE cardinality(allowed_roles) = 0;

UPDATE users
SET selected_location = farm_location,
    selected_latitude = farm_latitude,
    selected_longitude = farm_longitude
WHERE selected_location IS NULL
  AND farm_location IS NOT NULL
  AND farm_latitude IS NOT NULL
  AND farm_longitude IS NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'users_farm_latitude_range_check'
          AND conrelid = 'users'::regclass
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_farm_latitude_range_check
            CHECK (farm_latitude IS NULL OR farm_latitude BETWEEN -90 AND 90);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'users_farm_longitude_range_check'
          AND conrelid = 'users'::regclass
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_farm_longitude_range_check
            CHECK (farm_longitude IS NULL OR farm_longitude BETWEEN -180 AND 180);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'users_farm_coordinates_pair_check'
          AND conrelid = 'users'::regclass
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_farm_coordinates_pair_check
            CHECK (
                (farm_latitude IS NULL AND farm_longitude IS NULL) OR
                (farm_latitude IS NOT NULL AND farm_longitude IS NOT NULL)
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'users_allowed_roles_valid_check'
          AND conrelid = 'users'::regclass
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_allowed_roles_valid_check
            CHECK (
                cardinality(allowed_roles) > 0
                AND allowed_roles <@ ARRAY['farmer', 'owner']::TEXT[]
                AND role = ANY(allowed_roles)
            );
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'users_selected_latitude_range_check'
          AND conrelid = 'users'::regclass
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_selected_latitude_range_check
            CHECK (selected_latitude IS NULL OR selected_latitude BETWEEN -90 AND 90);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'users_selected_longitude_range_check'
          AND conrelid = 'users'::regclass
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_selected_longitude_range_check
            CHECK (selected_longitude IS NULL OR selected_longitude BETWEEN -180 AND 180);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'users_selected_coordinates_pair_check'
          AND conrelid = 'users'::regclass
    ) THEN
        ALTER TABLE users
            ADD CONSTRAINT users_selected_coordinates_pair_check
            CHECK (
                (selected_latitude IS NULL AND selected_longitude IS NULL) OR
                (selected_latitude IS NOT NULL AND selected_longitude IS NOT NULL)
            );
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION enforce_permanent_user_role()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.role IS DISTINCT FROM NEW.role THEN
        RAISE EXCEPTION 'User roles are permanent and cannot be changed after registration.';
    END IF;
    NEW.allowed_roles := ARRAY[NEW.role]::TEXT[];
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_enforce_permanent_user_role ON users;
CREATE TRIGGER trigger_enforce_permanent_user_role
BEFORE INSERT OR UPDATE ON users
FOR EACH ROW
EXECUTE FUNCTION enforce_permanent_user_role();

CREATE TABLE IF NOT EXISTS admin_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    password_changed_at TIMESTAMPTZ
);
ALTER TABLE admin_accounts ADD COLUMN IF NOT EXISTS token_version INTEGER NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS owner_access_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (lower(status) IN ('pending', 'approved', 'rejected', 'revoked')),
    request_note TEXT,
    review_note TEXT,
    reviewed_by BIGINT REFERENCES admin_accounts(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS owner_access_requests_one_pending_per_user_idx
    ON owner_access_requests(user_id)
    WHERE lower(status) = 'pending';

CREATE INDEX IF NOT EXISTS owner_access_requests_status_created_idx
    ON owner_access_requests(status, created_at DESC);

CREATE TABLE IF NOT EXISTS admin_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES admin_accounts(id) ON DELETE RESTRICT,
    action TEXT NOT NULL,
    entity_type TEXT NOT NULL,
    entity_id TEXT,
    outcome TEXT NOT NULL CHECK (outcome IN ('success', 'rejected')),
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS admin_audit_logs_created_idx
    ON admin_audit_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS admin_audit_logs_entity_idx
    ON admin_audit_logs(entity_type, entity_id, created_at DESC);

CREATE TABLE IF NOT EXISTS machinery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    type TEXT NOT NULL,
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    location TEXT NOT NULL,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    availability BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

ALTER TABLE machinery ADD COLUMN IF NOT EXISTS image_url TEXT;
ALTER TABLE machinery ADD COLUMN IF NOT EXISTS admin_active BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE machinery
    ADD COLUMN IF NOT EXISTS brand TEXT,
    ADD COLUMN IF NOT EXISTS model TEXT,
    ADD COLUMN IF NOT EXISTS description TEXT,
    ADD COLUMN IF NOT EXISTS price_unit TEXT NOT NULL DEFAULT 'day',
