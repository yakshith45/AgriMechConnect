CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    machinery_id BIGINT NOT NULL REFERENCES machinery(id) ON DELETE CASCADE,
    booking_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'rejected', 'completed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS rental_rate NUMERIC(12, 2),
    ADD COLUMN IF NOT EXISTS rental_unit TEXT,
    ADD COLUMN IF NOT EXISTS estimated_total NUMERIC(12, 2);

UPDATE bookings b
SET rental_rate = m.price,
    rental_unit = COALESCE(m.price_unit, 'day'),
    estimated_total = m.price
FROM machinery m
WHERE m.id = b.machinery_id
  AND (b.rental_rate IS NULL OR b.rental_unit IS NULL OR b.estimated_total IS NULL);

ALTER TABLE bookings
    ALTER COLUMN rental_rate SET NOT NULL,
    ALTER COLUMN rental_unit SET NOT NULL,
    ALTER COLUMN estimated_total SET NOT NULL;

CREATE INDEX IF NOT EXISTS machinery_owner_id_idx ON machinery(owner_id);
CREATE INDEX IF NOT EXISTS machinery_available_created_idx ON machinery(availability, created_at DESC);
CREATE INDEX IF NOT EXISTS bookings_farmer_created_idx ON bookings(farmer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS bookings_machinery_created_idx ON bookings(machinery_id, created_at DESC);
CREATE INDEX IF NOT EXISTS bookings_machinery_schedule_idx
    ON bookings (machinery_id, booking_date, start_time, end_time)
    WHERE status IN ('pending', 'accepted');

CREATE TABLE IF NOT EXISTS conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    machinery_id BIGINT NOT NULL REFERENCES machinery(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT conversations_distinct_participants CHECK (farmer_id <> owner_id),
    CONSTRAINT conversations_farmer_machinery_unique UNIQUE (farmer_id, machinery_id)
);

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message_text TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT messages_text_not_empty CHECK (LENGTH(TRIM(message_text)) > 0 AND LENGTH(message_text) <= 2000)
);

CREATE INDEX IF NOT EXISTS idx_conversations_farmer_updated ON conversations(farmer_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversations_owner_updated ON conversations(owner_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversations_machinery ON conversations(machinery_id);
CREATE INDEX IF NOT EXISTS idx_messages_conversation_id_created ON messages(conversation_id, created_at ASC);
CREATE INDEX IF NOT EXISTS idx_messages_unread ON messages(conversation_id, sender_id, is_read);

