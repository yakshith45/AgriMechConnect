-- 1. Enable required extensions
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT,
    password TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('farmer', 'owner')),
    farm_location TEXT,
    farm_latitude DOUBLE PRECISION CHECK (farm_latitude IS NULL OR farm_latitude BETWEEN -90 AND 90),
    farm_longitude DOUBLE PRECISION CHECK (farm_longitude IS NULL OR farm_longitude BETWEEN -180 AND 180),
    allowed_roles TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    selected_location TEXT,
    selected_latitude DOUBLE PRECISION CHECK (selected_latitude IS NULL OR selected_latitude BETWEEN -90 AND 90),
    selected_longitude DOUBLE PRECISION CHECK (selected_longitude IS NULL OR selected_longitude BETWEEN -180 AND 180),
    is_suspended BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT users_farm_coordinates_pair_check CHECK (
        (farm_latitude IS NULL AND farm_longitude IS NULL) OR
        (farm_latitude IS NOT NULL AND farm_longitude IS NOT NULL)
    ),
    CONSTRAINT users_selected_coordinates_pair_check CHECK (
        (selected_latitude IS NULL AND selected_longitude IS NULL) OR
        (selected_latitude IS NOT NULL AND selected_longitude IS NOT NULL)
    )
);

-- Enforce permanent user roles
CREATE OR REPLACE FUNCTION public.enforce_permanent_user_role()
RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.role IS DISTINCT FROM NEW.role THEN
        RAISE EXCEPTION 'User roles are permanent and cannot be changed after registration.';
    END IF;
    NEW.allowed_roles := ARRAY[NEW.role]::TEXT[];
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_enforce_permanent_user_role ON public.users;
CREATE TRIGGER trigger_enforce_permanent_user_role
BEFORE INSERT OR UPDATE ON public.users
FOR EACH ROW
EXECUTE FUNCTION public.enforce_permanent_user_role();

-- 3. Admin Accounts
CREATE TABLE IF NOT EXISTS public.admin_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    token_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    password_changed_at TIMESTAMPTZ
);

-- 4. Owner Access Requests
CREATE TABLE IF NOT EXISTS public.owner_access_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (lower(status) IN ('pending', 'approved', 'rejected', 'revoked')),
    request_note TEXT,
    review_note TEXT,
    reviewed_by BIGINT REFERENCES public.admin_accounts(id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS owner_access_requests_one_pending_per_user_idx
    ON public.owner_access_requests(user_id)
    WHERE lower(status) = 'pending';

CREATE INDEX IF NOT EXISTS owner_access_requests_status_created_idx
    ON public.owner_access_requests(status, created_at DESC);

-- 5. Admin Audit Logs
CREATE TABLE IF NOT EXISTS public.admin_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id BIGINT NOT NULL REFERENCES public.admin_accounts(id) ON DELETE RESTRICT,
    action TEXT NOT NULL,
    entity_type TEXT NOT NULL,
    entity_id TEXT,
    outcome TEXT NOT NULL CHECK (outcome IN ('success', 'rejected')),
    details JSONB NOT NULL DEFAULT '{}'::JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS admin_audit_logs_created_idx ON public.admin_audit_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS admin_audit_logs_entity_idx ON public.admin_audit_logs(entity_type, entity_id, created_at DESC);

-- 6. Machinery Inventory (with Cloudinary fields)
CREATE TABLE IF NOT EXISTS public.machinery (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    type TEXT NOT NULL,
    brand TEXT,
    model TEXT,
    description TEXT,
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    price_unit TEXT NOT NULL DEFAULT 'day' CHECK (price_unit IN ('hour', 'day', 'acre')),
    location TEXT NOT NULL,
    latitude DOUBLE PRECISION CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    longitude DOUBLE PRECISION CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
    image_url TEXT,
    cloudinary_public_id TEXT,
    specifications JSONB NOT NULL DEFAULT '{}'::JSONB,
    availability BOOLEAN NOT NULL DEFAULT TRUE,
    admin_active BOOLEAN NOT NULL DEFAULT TRUE,
    availability_start_date DATE,
    availability_end_date DATE,
    availability_start_time TIME,
    availability_end_time TIME,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS machinery_owner_id_idx ON public.machinery(owner_id);
CREATE INDEX IF NOT EXISTS machinery_available_created_idx ON public.machinery(availability, created_at DESC);

-- 7. Bookings
CREATE TABLE IF NOT EXISTS public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    machinery_id BIGINT NOT NULL REFERENCES public.machinery(id) ON DELETE CASCADE,
    booking_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    rental_rate NUMERIC(12, 2) NOT NULL,
    rental_unit TEXT NOT NULL,
    estimated_total NUMERIC(12, 2) NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'rejected', 'completed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS bookings_farmer_created_idx ON public.bookings(farmer_id, created_at DESC);
CREATE INDEX IF NOT EXISTS bookings_machinery_created_idx ON public.bookings(machinery_id, created_at DESC);
CREATE INDEX IF NOT EXISTS bookings_machinery_schedule_idx
    ON public.bookings (machinery_id, booking_date, start_time, end_time)
    WHERE status IN ('pending', 'accepted');

-- 8. Conversations & Messages (Realtime-Ready)
CREATE TABLE IF NOT EXISTS public.conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    owner_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    machinery_id BIGINT NOT NULL REFERENCES public.machinery(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT conversations_distinct_participants CHECK (farmer_id <> owner_id),
    CONSTRAINT conversations_farmer_machinery_unique UNIQUE (farmer_id, machinery_id)
);

CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES public.conversations(id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    message_text TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT messages_text_not_empty CHECK (LENGTH(TRIM(message_text)) > 0 AND LENGTH(message_text) <= 2000)
);

CREATE INDEX IF NOT EXISTS idx_conversations_farmer_updated ON public.conversations(farmer_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversations_owner_updated ON public.conversations(owner_id, updated_at DESC);
CREATE INDEX IF NOT EXISTS idx_conversations_machinery ON public.conversations(machinery_id);
CREATE INDEX IF NOT EXISTS idx_messages_conversation_id_created ON public.messages(conversation_id, created_at ASC);
CREATE INDEX IF NOT EXISTS idx_messages_unread ON public.messages(conversation_id, sender_id, is_read);

